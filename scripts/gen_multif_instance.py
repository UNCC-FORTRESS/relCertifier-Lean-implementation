"""Generator for plain multiF instances (λ = 1, k = 1, uniform invariant).

Emits a complete Lean instance file from a coordinate spec: defs, side-splits,
graph, windows, pins, field/dom pins, faces, odeField, Lie blocks, Lipschitz,
field bound, existence (stratified or stratA), and the climb-dispatch assembly.
"""

def gen(spec):
    N = spec['n']; SUF = spec['suf']; IR = spec['ir']; NS = spec['ns']
    BENCH = spec['bench']; THM = spec['thm']
    vars_lean = '[' + ', '.join(f'"{v}"' for v in spec['vars']) + ']'
    rows = spec['rows']            # i -> ('affine',) | ('bracket', p, t) | ('vel',) | ('decay',) | ('zero',)
    strict = spec['strict']        # [(coord, lo, hi, nameLo, nameHi)]
    aux = spec.get('aux', [])      # [(coord, lo, name)]  auxiliary strict lower face
    nonstrict = spec['nonstrict']  # [(coord, lo, hi, nameLo, nameHi)] zero-field bands
    s_face = spec.get('s_face')    # (coord, name) conditioned face, or None
    affineL = spec.get('affineL', [])   # [(coord,)] equilibrium lower faces
    dom = spec['dom']              # [(coord, lo, hi|None)]
    gs_idx = spec['gs']            # invariant atom indices, DC order (first is head)
    cst = spec['cst']              # per-mode drive constants as lean reals
    K = spec['K']; L = spec['L']
    nmodes = spec.get('nmodes', 3)
    pins = spec['pins']            # [(name, literal, lean_value, needs_norm)]
    hasBracket = any(r[0] == 'bracket' for r in rows.values())

    # coordinates with a non-zero row, in field-if order
    nz = [i for i in sorted(rows) if rows[i][0] != 'zero']

    def negs(j):
        return [k for k in nz if nz.index(k) < nz.index(j)] if j in nz else nz

    def ifnegs(j):
        return "".join(f"if_neg (hne {j} {k} (by decide)), " for k in negs(j))

    def rowval(i, xs='x'):
        kind = rows[i]
        if kind[0] == 'affine':
            return f'3 * (cst{SUF} q - {xs} (Rv {i}))'
        if kind[0] == 'vel':
            return f'{xs} (Rv 0)'
        if kind[0] == 'bracket':
            _, p, t = kind
            return (f'{xs} (Rv 0) * ((1 - 1/2 * ({xs} (Rv {p}) * {xs} (Rv {p})))'
                    f' - 3/10 * ({xs} (Rv {t}) * {xs} (Rv {t})))')
        if kind[0] == 'decay':
            return f'-1 * {xs} (Rv {i})'
        return '0'

